/** Generate the employee tools from the authoritative, inspectable Standard preset. */
import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../presets/standard.patch.yml', import.meta.url)
const target = new URL('../presets/standard-tools.yml', import.meta.url)
const text = readFileSync(source, 'utf8')
const marker = '          - id: agent-instructions\n'
const start = text.indexOf(marker)
if (start < 0 || text.indexOf(marker, start + marker.length) !== -1) {
  throw new Error('Standard tools need one agent-instructions row following the persona')
}
const rows = text.slice(start).split('\n').map(line => line.startsWith('          ') ? line.slice(10) : line).join('\n')
const generated = '# Generated by scripts/generate-standard-tools.mjs from standard.patch.yml; edit the Standard preset.\n' + rows
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Regenerate presets/standard-tools.yml')
} else {
  writeFileSync(target, generated)
}
