import { appPath } from '@deepseek-ai/dsh-client-ui-primitives'
import type { Post, Comment } from './types.ts'

/** Non-authorizing account guards; the Host owns all Bearer credentials. */
export interface Owner {
  readonly id: string
  readonly owner: string
  readonly epoch: number
}
/** Forum transport rejection, including unknown publication outcome. */
export class ForumFailure extends Error {
  constructor(
    readonly code: string,
    readonly uncertain = false,
  ) {
    super(code)
  }
}
function object(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value))
    throw new ForumFailure('FORUM_PROTOCOL', true)
  return value as Record<string, unknown>
}
function text(value: unknown, limit: number): string {
  if (typeof value !== 'string' || value.length > limit) throw new ForumFailure('FORUM_PROTOCOL', true)
  return value
}
function integer(value: unknown): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0)
    throw new ForumFailure('FORUM_PROTOCOL', true)
  return value
}
/**
 * Decode a public forum post.
 * @param value - Public content received over the wire.
 * @returns Validated post projection.
 */
export function post(value: unknown): Post {
  const row = object(value),
    author = object(row.author)
  if (typeof row.liked !== 'boolean') throw new ForumFailure('FORUM_PROTOCOL', true)
  return {
    id: text(row.id, 40),
    title: text(row.title, 800),
    body: text(row.body, 80_000),
    author: { id: integer(author.id), display_name: text(author.display_name, 800) },
    created_at: integer(row.created_at),
    like_count: integer(row.like_count),
    comment_count: integer(row.comment_count),
    liked: row.liked,
  }
}
/**
 * Decode a public forum comment.
 * @param value - Public reply received over the wire.
 * @returns Validated comment projection.
 */
export function comment(value: unknown): Comment {
  const row = object(value),
    author = object(row.author)
  return {
    id: text(row.id, 40),
    post_id: text(row.post_id, 40),
    body: text(row.body, 16_000),
    author: { id: integer(author.id), display_name: text(author.display_name, 800) },
    created_at: integer(row.created_at),
  }
}
/**
 * Decode a bounded cursor page.
 * @param value - Cursor page received over the wire.
 * @param decode - Item decoder.
 * @returns Validated items and the next cursor.
 */
export function page<T>(value: unknown, decode: (item: unknown) => T): { items: T[]; cursor: string } {
  const row = object(value)
  if (!Array.isArray(row.items) || row.items.length > 100 || typeof row.has_more !== 'boolean')
    throw new ForumFailure('FORUM_PROTOCOL', true)
  return { items: row.items.map(decode), cursor: row.has_more ? text(row.next_cursor, 256) : '' }
}
/**
 * Send once through the exact local Host route and verify account ownership on the response.
 * @param owner - Captured login identity, never a credential.
 * @param path - Forum suffix generated by the controller.
 * @param method - Read, publication, or desired like state.
 * @param body - Immutable publication data.
 * @param signal - Complete lifetime controlled by the account owner.
 * @returns The public forum payload; rejects without automatically replaying a write.
 */
export async function request(
  owner: Owner,
  path: string,
  method: 'GET' | 'POST' | 'PUT',
  body: unknown,
  signal: AbortSignal,
): Promise<Record<string, unknown>> {
  try {
    const r = await fetch(appPath('/credits/api/forum' + path), {
      method,
      signal,
      cache: 'no-store',
      credentials: 'same-origin',
      headers: {
        'content-type': 'application/json',
        'x-yunshu-account-id': owner.id,
        'x-yunshu-account-owner': owner.owner,
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    })
    const raw = await r.text()
    if (raw.length > 4 * 1024 * 1024) throw new ForumFailure('FORUM_PROTOCOL', true)
    const row = object(JSON.parse(raw) as unknown)
    if (
      row.account !== undefined &&
      (object(row.account).id !== owner.id || row.accountOwner !== owner.owner)
    )
      throw new ForumFailure('ACCOUNT_CHANGED', true)
    if (!r.ok || row.ok !== true)
      throw new ForumFailure(
        typeof row.code === 'string' ? row.code : 'FORUM_UNAVAILABLE',
        row.outcome === 'unknown' || r.status >= 500,
      )
    if (object(row.account).id !== owner.id || row.accountOwner !== owner.owner)
      throw new ForumFailure('ACCOUNT_CHANGED', true)
    return object(row.payload)
  } catch (error) {
    throw error instanceof ForumFailure ? error : new ForumFailure('FORUM_NETWORK', true)
  }
}
